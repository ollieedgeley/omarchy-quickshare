import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { tmpdir } from "node:os";
import test from "node:test";

import {
  configurationFailures,
  generatedProvenanceFailures,
  structureScope,
} from "../structure.mjs";

test("generated wire bindings require declared pinned provenance", () => {
  const directory = mkdtempSync(join(tmpdir(), "quickshare-provenance-"));
  const path = "crates/core/wire/src/generated/binding.rs";
  try {
    const output = join(directory, path);
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(
      output,
      "// Generated by tools/codegen/quickshare-wire.\n" +
        "// Inputs: upstream/sources.toml#google-nearby, google-ukey2.\n",
    );
    assert.deepEqual(
      generatedProvenanceFailures([path], { root: directory }),
      [],
    );
    writeFileSync(output, "// Generated by tools/codegen/quickshare-wire.\n");
    assert.deepEqual(generatedProvenanceFailures([path], { root: directory }), [
      `${path}: missing pinned input provenance`,
    ]);
    writeFileSync(output, "// Generated by unknown tool.\n");
    assert.deepEqual(generatedProvenanceFailures([path], { root: directory }), [
      `${path}: missing generator provenance header`,
    ]);
  } finally {
    rmSync(directory, { force: true, recursive: true });
  }
});

test("structure scopes keep application and tooling feedback separate", () => {
  assert.equal(structureScope("crates/core/src/lib.rs"), "app");
  assert.equal(structureScope("packaging/omarchy-plugin/Main.qml"), "app");
  assert.equal(
    structureScope("tests/environments/android/driver.mjs"),
    "tooling",
  );
  assert.equal(structureScope("tools/hooks/run-staged.mjs"), "tooling");
});

test("formatter and linter metric settings agree", async () => {
  assert.deepEqual(await configurationFailures(), []);
});

test("application configuration accepts CI and a changed toolchain pin", () => {
  const directory = mkdtempSync(join(tmpdir(), "quickshare-config-"));
  try {
    mkdirSync(join(directory, ".github", "workflows"), { recursive: true });
    writeFileSync(
      join(directory, "rust-toolchain.toml"),
      '[toolchain]\nchannel = "1.99.0"\n' +
        'components = ["clippy", "rust-analyzer", "rustfmt"]\n',
    );
    writeFileSync(join(directory, "rustfmt.toml"), "max_width = 80\n");
    writeFileSync(
      join(directory, "clippy.toml"),
      "too-many-lines-threshold = 50\n",
    );
    writeFileSync(
      join(directory, "sgconfig.yml"),
      "ruleDirs: []\ntestConfigs: []\nutilDirs: []\n",
    );
    const moduleUrl = new URL(
      "../structure-configuration.mjs",
      import.meta.url,
    );
    const source = JSON.stringify(moduleUrl.href);
    const script = `import { configurationFailures } from ${source};
      console.log(JSON.stringify(await configurationFailures("app")));`;
    const result = spawnSync(
      process.execPath,
      ["--input-type=module", "-e", script],
      {
        encoding: "utf8",
        env: { ...process.env, GATE_ROOT: directory },
      },
    );
    assert.equal(result.status, 0, result.stderr);
    assert.deepEqual(JSON.parse(result.stdout), []);
  } finally {
    rmSync(directory, { force: true, recursive: true });
  }
});
