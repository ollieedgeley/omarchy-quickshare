import { existsSync, readFileSync, readdirSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { configurationFailures } from "./structure-configuration.mjs";
import { output } from "./lib/process.mjs";

export { configurationFailures } from "./structure-configuration.mjs";

const SCRIPT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ROOT = resolve(process.env.GATE_ROOT ?? SCRIPT_ROOT);
const EXCLUDED_NAMES = new Set([
  ".cache",
  ".codegraph",
  ".git",
  "dist",
  "node_modules",
  "reports",
  "target",
]);
const GENERATED_RUST = [
  {
    generator: "// Generated by tools/codegen/quickshare-wire.",
    inputs: "// Inputs: upstream/sources.toml#google-nearby, google-ukey2.",
    prefix: "crates/core/wire/src/generated/",
  },
];
const APPLICATION_PREFIXES = [
  "crates/",
  "fuzz/",
  "packaging/",
  "rules/ast-grep/",
];
const APPLICATION_FILES = new Set([
  "Cargo.lock",
  "Cargo.toml",
  "clippy.toml",
  "rust-toolchain.toml",
  "rustfmt.toml",
  "sgconfig.yml",
]);

function walkFiles(directory, base = directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!EXCLUDED_NAMES.has(entry.name) && entry.name !== "_") {
      const absolute = join(directory, entry.name);
      if (entry.isDirectory()) {
        files.push(...walkFiles(absolute, base));
      }
      if (entry.isFile()) {
        files.push(relative(base, absolute).split(sep).join("/"));
      }
    }
  }
  return files;
}

function repositoryFiles() {
  if (!existsSync(join(ROOT, ".git"))) {
    return walkFiles(ROOT);
  }
  const listed = output(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    { cwd: ROOT },
  );
  if (listed) {
    return listed.split("\0").filter(Boolean);
  }
  return [];
}

function generatedRustProvenance(path) {
  if (!path.endsWith(".rs")) {
    return null;
  }
  return GENERATED_RUST.find(({ prefix }) => path.startsWith(prefix)) ?? null;
}

export function generatedProvenanceFailures(files, options = {}) {
  const root = options.root ?? ROOT;
  const failures = [];
  for (const path of files) {
    const provenance = generatedRustProvenance(path);
    if (provenance) {
      const source = readFileSync(join(root, path), "utf8");
      const header = [provenance.generator, provenance.inputs, ""].join("\n");
      if (!source.startsWith(provenance.generator)) {
        failures.push(`${path}: missing generator provenance header`);
      } else if (!source.startsWith(header)) {
        failures.push(`${path}: missing pinned input provenance`);
      }
    }
  }
  return failures;
}

export function structureScope(path) {
  if (
    APPLICATION_FILES.has(path) ||
    APPLICATION_PREFIXES.some((prefix) => path.startsWith(prefix))
  ) {
    return "app";
  }
  return "tooling";
}

export async function checkStructure(scope = "all") {
  if (!["all", "app", "tooling"].includes(scope)) {
    throw new Error(`unknown structure scope: ${scope}`);
  }
  let files = repositoryFiles();
  if (scope !== "all") {
    files = files.filter((path) => structureScope(path) === scope);
  }
  return [
    ...generatedProvenanceFailures(files),
    ...(await configurationFailures()),
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const scope = process.argv[2] ?? "all";
  const failures = await checkStructure(scope);
  if (failures.length) {
    process.stderr.write(`${failures.join("\n")}\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`Repository ${scope} structure contracts passed.\n`);
  }
}
